async function main() {
  console.log('========================================================');
  console.log('🏛️ دەستکرا بە چاککردنی ناوی گەڕەکەکان و سڕینەوەی دەرەوەی سلێمانی...');
  console.log('========================================================\n');

  console.log('🔑 لۆگین وەرگرتنی تۆکنی ئەدمین لە Supabase...');
  const token = await getAdminToken();
  console.log('✅ تۆکنی ئەدمین وەرگیرا.\n');

  const headers = {
    'Content-Type': 'application/json',
    apikey: SUPABASE_ANON_KEY,
    Authorization: `Bearer ${token}`,
  };

  // 1. Update properties table so all 245 properties have clean canonical Sulaymaniyah neighborhood names
  console.log('🔄 قۆناغی یەکەم: نوێکردنەوەی ناوی گەڕەکی موڵکەکان (Properties)...');
  const propRes = await fetch(`${SUPABASE_URL}/rest/v1/properties?select=id,code,neighborhood,title`, {
    headers: { apikey: SUPABASE_ANON_KEY },
  });
  if (!propRes.ok) throw new Error(`Failed to fetch properties: ${await propRes.text()}`);
  const properties = await propRes.json();
  console.log(`📊 کۆی موڵکەکان: ${properties.length}`);

  let updatedPropsCount = 0;
  for (const p of properties) {
    let cleanNeighborhood = p.neighborhood;
    if (p.neighborhood === 'سلێمانی' && SLEMANI_GENERIC_CODE_MAP[p.code]) {
      cleanNeighborhood = SLEMANI_GENERIC_CODE_MAP[p.code];
    } else if (PROPERTY_NEIGHBORHOOD_MAPPING[p.neighborhood]) {
      cleanNeighborhood = PROPERTY_NEIGHBORHOOD_MAPPING[p.neighborhood];
    }

    if (cleanNeighborhood !== p.neighborhood) {
      const patchRes = await fetch(`${SUPABASE_URL}/rest/v1/properties?id=eq.${p.id}`, {
        method: 'PATCH',
        headers,
        body: JSON.stringify({ neighborhood: cleanNeighborhood }),
      });
      if (!patchRes.ok) {
        console.error(`❌ نەتوانرا موڵکی #${p.code} نوێ بکرێتەوە: ${await patchRes.text()}`);
      } else {
        updatedPropsCount++;
      }
    }
  }
  console.log(`✅ ${updatedPropsCount} موڵک ناوی گەڕەکەکەی نوێکرایەوە بۆ ناوی ستاندارد.\n`);

  // 2. Delete non-Sulaymaniyah neighborhoods from `neighborhoods` table
  console.log('🗑️ قۆناغی دووەم: سڕینەوەی گەڕەک و شارۆچکەکانی دەرەوەی سلێمانی...');
  const nonSlemaniCities = ['chamchamal', 'halabja', 'kalar', 'ranya', 'dukan', 'penjwen', 'said_sadiq'];
  for (const city of nonSlemaniCities) {
    const delRes = await fetch(`${SUPABASE_URL}/rest/v1/neighborhoods?city=eq.${city}`, {
      method: 'DELETE',
      headers,
    });
    if (!delRes.ok) {
      console.error(`❌ هەڵە لە سڕینەوەی شارۆچکەی ${city}: ${await delRes.text()}`);
    } else {
      console.log(`   - سڕینەوەی سەرجەم ناوچەکانی [${city}] تەواو بوو.`);
    }
  }

  // 3. Delete non-Sulaymaniyah road artifacts, highway entries, and distance entries (>20km)
  console.log('\n🧹 قۆناغی سێیەم: پاککردنەوەی ناوی ڕێگاکان و شوێنە ناپێویستەکان...');
  const junkPrefixes = ['ڕێگای %', 'ڕیگای %', 'ڕێگاى %', 'شاڕێی %', '119-%', 'H_%', '%Street%'];
  for (const pattern of junkPrefixes) {
    const delJunk = await fetch(`${SUPABASE_URL}/rest/v1/neighborhoods?name=like.${encodeURIComponent(pattern)}`, {
      method: 'DELETE',
      headers,
    });
    if (delJunk.ok) {
      console.log(`   - سڕینەوەی [${pattern}] ئەنجامدرا.`);
    }
  }

  // Also purge any distant entries or entries with "گەرەکی " or "گەڕەکی " that will be replaced by canonical
  const oldPrefixes = ['گەرەکی %', 'گەڕەکی %'];
  for (const p of oldPrefixes) {
    await fetch(`${SUPABASE_URL}/rest/v1/neighborhoods?name=like.${encodeURIComponent(p)}`, {
      method: 'DELETE',
      headers,
    });
  }

  // 4. Upsert all canonical Sulaymaniyah neighborhoods
  console.log('\n🌟 قۆناغی چوارەم: تۆمارکردن و نوێکردنەوەی گەڕەک و شوێنە ستانداردەکانی سلێمانی...');
  let upsertedCount = 0;
  for (const n of CANONICAL_SLEMANI_NEIGHBORHOODS) {
    // Check if neighborhood exists by name
    const checkRes = await fetch(
      `${SUPABASE_URL}/rest/v1/neighborhoods?name=eq.${encodeURIComponent(n.name)}&select=id`,
      { headers: { apikey: SUPABASE_ANON_KEY } }
    );
    const existing = await checkRes.json();

    if (existing && existing.length > 0) {
      // Update existing
      const updateRes = await fetch(`${SUPABASE_URL}/rest/v1/neighborhoods?id=eq.${existing[0].id}`, {
        method: 'PATCH',
        headers,
        body: JSON.stringify({
          city: 'sulaymaniyah',
          nameKu: n.nameKu,
          nameEn: n.nameEn,
          nameAr: n.nameAr,
          latitude: n.latitude,
          longitude: n.longitude,
          aliases: n.aliases,
        }),
      });
      if (updateRes.ok) upsertedCount++;
    } else {
      // Insert new
      const insertRes = await fetch(`${SUPABASE_URL}/rest/v1/neighborhoods`, {
        method: 'POST',
        headers,
        body: JSON.stringify({
          id: crypto.randomUUID(),
          name: n.name,
          city: 'sulaymaniyah',
          nameKu: n.nameKu,
          nameEn: n.nameEn,
          nameAr: n.nameAr,
          latitude: n.latitude,
          longitude: n.longitude,
          aliases: n.aliases,
        }),
      });
      if (insertRes.ok) upsertedCount++;
      else {
        console.error(`❌ نەتوانرا [${n.name}] زیاد بکرێت: ${await insertRes.text()}`);
      }
    }
  }
  console.log(`✅ سەرجەم ${upsertedCount} گەڕەک و ناوچەی سەرەکی سلێمانی بە سەرکەوتوویی تۆمار و نوێکرانەوە.`);

  // 5. Verification
  console.log('\n📊 قۆناغی پێنجەم: پشکنین و دڵنیابوونەوە لە ئەنجامەکان...');
  const countRes = await fetch(`${SUPABASE_URL}/rest/v1/neighborhoods?select=id,name,city`, {
    headers: { apikey: SUPABASE_ANON_KEY },
  });
  const allFinal = await countRes.json();
  const cities = new Set(allFinal.map((x: any) => x.city));
  console.log(`   - کۆی گشتی گەڕەکەکان لە داتابەیس: ${allFinal.length}`);
  console.log(`   - شارە بەردەستەکان: ${[...cities].join(', ')}`);

  // Verify all properties now have matching neighborhood in DB
  const finalPropRes = await fetch(`${SUPABASE_URL}/rest/v1/properties?select=neighborhood`, {
    headers: { apikey: SUPABASE_ANON_KEY },
  });
  const finalProps = await finalPropRes.json();
  const finalNeighNames = new Set(allFinal.map((x: any) => x.name));
  const unmatched = [...new Set(finalProps.map((p: any) => p.neighborhood))].filter((n) => !finalNeighNames.has(n));

  if (unmatched.length === 0) {
    console.log(`🎉 سەرکەوتوو بوو! هەموو (${finalProps.length}) موڵکەکان بەتەواوی لەگەڵ گەڕەکەکانی سلێمانی دەگونجێن!`);
  } else {
    console.warn(`⚠️ ئەمانە هێشتا نەدۆزرانەوە لە گەڕەکەکان:`, unmatched);
  }

  console.log('\n========================================================');
  console.log('✨ پرۆسەکە بە سەرکەوتوویی کۆتایی هات.');
  console.log('========================================================');
}

main().catch(console.error);
